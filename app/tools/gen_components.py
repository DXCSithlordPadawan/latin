def bullets(xs):
    return "\n".join(f"- {x}" for x in xs)

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows_idx, rows_reg = [], []
    for key, (title, layer, purpose, files, ins, outs, ctl, std, gaps, tests) in COMP.items():
        body = f"""# {title}

{HDR}
| | |
|---|---|
| **Layer** | {layer} |
| **Purpose** | {purpose} |

## Files

{bullets('`'+f+'`' for f in files)}

## Inputs and outputs

| Inputs | Outputs |
|---|---|
| {'<br>'.join(ins)} | {'<br>'.join(outs)} |

## Controls present in the code

{bullets(ctl)}

## Standards

{bullets(std)}

## Gaps

{bullets(gaps)}

## Tests

{bullets(tests)}

## Diagram

```mermaid
flowchart LR
    IN["{ins[0].replace('"','')}"] --> C["{title.replace('"','')}"]
    C --> OUT["{outs[0].replace('"','').replace('`','')}"]
```
"""
        (OUT / f"{key}-Architecture.md").write_text(body, encoding="utf-8")
        rows_idx.append(f"| [{key}-Architecture]({key}-Architecture.md) | {title} | {layer} |")
        rows_reg.append(f"| {title} | {layer} | {', '.join('`'+f+'`' for f in files[:3])} | {len(gaps)} | [{key}-Architecture](components/{key}-Architecture.md) |")

    (OUT / "README.md").write_text(
        "# Component Architecture Documents\n\n" + HDR +
        "\nOne document per component; the main document is [DOC-01](../DOC-01-Architecture-Guide.md).\n\n"
        "| Document | Component | Layer |\n|---|---|---|\n" + "\n".join(rows_idx) + "\n", encoding="utf-8")

    (ROOT / "docs" / "component-register.md").write_text(
        "# Component Register\n\n" + HDR.replace("(../../../prd.md)", "(../../prd.md)").replace("(../DOC-01", "(DOC-01").replace("(../standards", "(standards") +
        "\n| Component | Layer | Main files | Open gaps | Document |\n|---|---|---|---|---|\n" + "\n".join(rows_reg) + "\n", encoding="utf-8")
    print(f"wrote {len(COMP)} component docs")

if __name__ == "__main__":
    main()

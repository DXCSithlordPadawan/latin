    frow = "\n".join(f"| {fid_name[f[0]]} | {f[1]} | {f[2]} | {f[3]} | {', '.join(f[4])} | {f[10] or '—'} | {f[11] or '—'} |" for f in F)
    (BRD / "latin_features.md").write_text(
        "# Latin Translator — Features\n\n" + HDR + "\n| FEAT | EP | Stage | Feature | Requirements | OD | Gap |\n|---|---|---|---|---|---|---|\n" + frow + "\n", encoding="utf-8")


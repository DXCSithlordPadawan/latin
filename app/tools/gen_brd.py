def asserts(ids, ntasks):
    ok = True

    def check(name, cond, detail=""):
        nonlocal ok
        print(("PASS " if cond else "FAIL ") + name + (" " + detail if detail and not cond else ""))
        ok = ok and cond

    # 1 every PRD requirement traced to a feature
    reqs_md = (BRD / "latin_reqs.md").read_text(encoding="utf-8")
    traced = dict(re.findall(r"^\| ((?:FR-[A-Z]+-\d+)|(?:NFR-\d+)) \| ([^|]*) \|", reqs_md, re.M))
    untraced = [r for r in ids if "NONE" in traced.get(r, "NONE")]
    check("1 every PRD requirement has a feature", not untraced, str(untraced))
    # 2 every traced ID exists in the PRD
    extra = [r for r in traced if r not in ids]
    check("2 no traced ID missing from the PRD", not extra, str(extra))
    # 3 every feature has a story and a task, and every story has persona that exists
    feat_md = (BRD / "latin_features.md").read_text(encoding="utf-8")
    story_md = (BRD / "latin_stories.md").read_text(encoding="utf-8")
    task_md = (BRD / "latin_tasks.md").read_text(encoding="utf-8")
    feats = re.findall(r"^\| (FEAT-\d+) \|", feat_md, re.M)
    s_feats = set(re.findall(r"^\| US-\d+ \| (FEAT-\d+) \|", story_md, re.M))
    s_ids = re.findall(r"^\| (US-\d+) \|", story_md, re.M)
    t_us = set(re.findall(r"^\| TASK-\d+ \| (US-\d+) \|", task_md, re.M))
    check("3 every feature has a story and every story a task", set(feats) == s_feats and set(s_ids) == t_us)
    # 4 plan totals equal files
    plan = (BRD / "latin_plan.md").read_text(encoding="utf-8")
    m = re.search(r"\*\*Total\*\* \| (\d+) epics \| (\d+) \| (\d+) \| (\d+)", plan)
    pts = sum(int(x) for x in re.findall(r"^\| US-\d+ \|.*\| (\d+) \|[^|]*\|$", story_md, re.M))
    check("4 plan totals equal generated files", bool(m) and int(m.group(2)) == len(feats) and int(m.group(3)) == pts and int(m.group(4)) == ntasks == len(re.findall(r"^\| TASK-\d+ ", task_md, re.M)),
          f"{m.groups() if m else None} feats={len(feats)} pts={pts} tasks={ntasks}")
    # 5 every epic has features and every BV has epics
    epic_md = (BRD / "latin_epics.md").read_text(encoding="utf-8")
    empty = [e for e in EP if not re.search(rf"^\| {e} \|.*FEAT-\d+", epic_md, re.M)]
    bvm = (BRD / "latin_BVM.md").read_text(encoding="utf-8")
    nobv = [b for b in BV if not re.search(rf"^\| {b} \|.*EP-\d+", bvm, re.M)]
    check("5 every epic has features and every BV has epics", not empty and not nobv, str(empty + nobv))
    print("counts:", len(BV), "BV", len(P), "personas", len(EP), "epics", len(F), "features", ntasks, "tasks", len(ids), "requirements")
    return 0 if ok else 1



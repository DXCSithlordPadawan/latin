        for f in ep_feats[e]:
            tk = ", ".join(t[0] for t in tasks if t[5] == f[0])
            links.append(f"| {fid_name[f[0]]} {f[3]} | {', '.join(f[4])} | {us[f[0]]} | {tk} |")

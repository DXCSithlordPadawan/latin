    srow = []
    for f in F:
        who = P[f[5]][0]
        srow.append(f"| {us[f[0]]} | {fid_name[f[0]]} | {f[5]} | As {who} I want {f[6]} so that {f[7]}. | {f[8]} | {f[9]} |")
    (BRD / "latin_stories.md").write_text(
        "# Latin Translator — User Stories\n\n" + HDR + "\n| US | FEAT | Persona | Story | Points | Key acceptance |\n|---|---|---|---|---|---|\n" + "\n".join(srow) + "\n", encoding="utf-8")

    # Tasks
    trow = "\n".join(f"| {t[0]} | {t[1]} | {t[2]} | {t[3]} | {t[4]} |" for t in tasks)
    (BRD / "latin_tasks.md").write_text(
        "# Latin Translator — Tasks\n\n" + HDR + "\nSize: S up to one day, M up to three days, L up to one week.\n\n| TASK | US | Stage | Task | Size |\n|---|---|---|---|---|\n" + trow + "\n", encoding="utf-8")

